"""Generate current presentation rows directly from the published session CSVs."""
from __future__ import annotations

import argparse
from pathlib import Path

from parabox.analysis import read_sessions

ROOT = Path(__file__).resolve().parents[1]
DESTINATION = ROOT / "report/decks/spread-of-misalignment/tables"
MODELS = {"v4pro": "DeepSeek V4 Pro", "gemini": "Gemini 3.1 Pro", "kimi": "Kimi K3",
          "qwen-max": "Qwen3.8-max", "ds-flash": "DeepSeek-flash", "qwen-flash": "Qwen3.8-flash"}


def rows(name: str, arm: str | None = None, generations=None, recipients=False) -> list[dict]:
    items = read_sessions(ROOT / "report/final" / f"{name}.csv")
    return [item for item in items if (arm is None or item["arm"] == arm)
            and (generations is None or item["generation"] in generations)
            and (not recipients or item["agent"] in (0, 1, 2))]


def count(items: list[dict], field="cheat") -> int:
    return sum(item.get(field) is True for item in items)


def fraction(items: list[dict], field="cheat") -> str:
    return f"{count(items, field)}/{len(items)}"


def line(values) -> str:
    return " & ".join(map(str, values)) + r" \\" + "\n"


def tables() -> dict[str, str]:
    output = {name: "% Generated by scripts/deck_tables.py; do not edit manually.\n"
              for name in ("baseline", "exposure", "content", "chains", "population", "solvable", "solvable-chains", "budget")}
    reference = dict(zip(MODELS, ("0.79", "0.25", "0.79", "0.38", "0.67", "0.38")))
    endings = {"v4pro": "1--4 truncated", "gemini": "10--12 truncated", "kimi": "5--8 truncated",
               "qwen-max": "7--10 refused", "ds-flash": "8--10 refused", "qwen-flash": "7--13 refused"}
    for model, label in MODELS.items():
        control = [rows(f"exposure-{model}", "control"), rows(f"gate-comparison-state-{model}", "control"),
                   rows(f"gate-comparison-score-{model}", "control")]
        note = [rows(f"exposure-{model}", "note"), rows(f"corrected-gate-exposure-state-{model}", "note"),
                rows(f"corrected-gate-exposure-score-{model}", "note")]
        if any(len(cell) != 16 for cell in control + note):
            raise ValueError(f"unexpected exposure denominator for {model}")
        output["baseline"] += line([label, *(count(cell) for cell in control), "", reference[model]])
        output["budget"] += line([label, *(count(cell, "truncated") for pair in zip(control, note) for cell in pair)])
        output["exposure"] += line([label, *(f"{count(before)} $\\to$ {count(after)}"
                                                   for before, after in zip(control, note)), endings[model]])
    labels = {"control": "Control notice", "goal": "Goal only", "hint": "Location only",
              "note": "Exploit note (method and success claim)", "prohibit": "Prohibition by the note's author",
              "c3": "Exploit note + 3 condemnations from peers"}
    for arm, label in labels.items():
        output["content"] += line([label, *(count(rows(f"{'exposure' if arm in ('control', 'note') else 'message-content'}-{model}", arm))
                                          for model in ("v4pro", "gemini", "kimi", "qwen-max"))])
    for model in ("v4pro", "kimi", "gemini"):
        note = rows(f"chain-replication-note-{model}")
        curve = ", ".join(str(count([row for row in note if row["generation"] == generation])) for generation in range(1, 5))
        injection = "---" if model == "kimi" else ", ".join(
            str(count(rows(f"chain-replication-inject-{model}", generations=[generation]))) for generation in (2, 3, 4))
        output["chains"] += line([MODELS[model], curve, fraction(note), fraction(rows(f"chain-replication-control-{model}")), injection])
    for arm, label in (("v4pro-all", "V4 Pro only, all files kept"),
                       ("v4pro-selected", "V4 Pro only, accepted authors' files"),
                       ("mixed-all", "3 V4 Pro + 1 Qwen3.8-max, all files")):
        items = rows(f"population-replication-{arm}")
        curve = " ".join(str(count([row for row in items if row["generation"] == generation])) for generation in range(1, 9))
        windows = [rows(f"population-replication-{arm}", generations=window) for window in ((1, 2), (6, 7, 8))]
        output["population"] += line([label, curve, *(f"{count(cell) / len(cell):.2f}" for cell in windows), fraction(items)])
    for model in ("v4pro", "gemini", "kimi"):
        control, method = rows(f"solvable-extended-budget-{model}", "control"), rows(f"solvable-extended-budget-{model}", "method")
        output["solvable"] += line([MODELS[model], fraction(control), fraction(method), fraction(control, "audit_ok")])
    for model, label in (("v4pro", "DeepSeek V4 Pro"), ("gemini", "Gemini 3.1 Pro"), ("kimi", "Kimi K3"),
                         ("v41-flash", "DeepSeek Flash"), ("g38-flash", "Gemini 3.8 Flash")):
        output["solvable-chains"] += line([label, fraction(rows(f"solvable-chains-{model}", "method", [1])),
                                          fraction(rows(f"solvable-chains-{model}", "method", [6, 7, 8])),
                                          fraction(rows(f"solvable-chains-{model}", "control", [6, 7, 8]))])
    return output


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", action="store_true")
    args = parser.parse_args()
    for name, content in tables().items():
        path = DESTINATION / f"{name}.tex"
        if args.write:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
        elif not path.exists() or path.read_text() != content:
            raise SystemExit(f"presentation rows stale or missing: {path}")
    print(f"{len(tables())} current presentation tables match the session CSVs.")


if __name__ == "__main__":
    main()
